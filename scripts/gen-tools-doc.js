// 由 catalog.js 生成 docs/tools.md，保证文档与端点表始终一致。
// 用法：node scripts/gen-tools-doc.js
import { writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CATALOG, READ_ONLY_COUNT, WRITE_COUNT, ADMIN_COUNT } from "../catalog.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const GROUPS = [
  ["Connection & identity", (n) => n === "alist_me" || n.startsWith("alist_public_")],
  ["File browsing (read-only)", (n) => /^alist_fs_(list|get|dirs|search|archive_meta|archive_list|link)$/.test(n)],
  ["File write operations", (n) => n.startsWith("alist_fs_")],
  ["Tasks", (n) => n.startsWith("alist_task_")],
  ["Storage (admin)", (n) => n.startsWith("alist_admin_storage_")],
  ["Drivers (admin, read-only)", (n) => n.startsWith("alist_admin_driver_")],
  ["Users (admin)", (n) => n.startsWith("alist_admin_user_")],
  ["Roles (admin)", (n) => n.startsWith("alist_admin_role_")],
  ["Metadata (admin)", (n) => n.startsWith("alist_admin_meta_")],
  ["Site settings (admin)", (n) => n.startsWith("alist_admin_setting_")],
  ["Search index (admin)", (n) => n.startsWith("alist_admin_index_")],
  ["Sessions & messages (admin)", (n) => n.startsWith("alist_admin_session_") || n.startsWith("alist_admin_message_")],
  ["Shares", (n) => n.startsWith("alist_share_")],
  ["Labels (read-only)", (n) => n.startsWith("alist_label_")],
];

const SPECIAL = [
  {
    name: "alist_fs_put",
    method: "PUT",
    path: "/api/fs/put",
    kind: "write",
    description: "Stream a local file (Host-side absolute path) to AList. Respects maxUploadBytes. Honours As-Task.",
  },
  {
    name: "alist_fs_form",
    method: "PUT",
    path: "/api/fs/form",
    kind: "write",
    description: "Upload a local file as multipart/form-data, for drivers that require a form upload.",
  },
];

function paramList(params) {
  return Object.entries(params ?? {})
    .map(([k, v]) => `${k}${v.required ? "*" : ""}`)
    .join(", ");
}

const lines = [];
lines.push("# dsh-alist tool reference");
lines.push("");
lines.push("Generated by `node scripts/gen-tools-doc.js` — do not edit by hand.");
lines.push("");
lines.push(
  `Baseline: AList **v3.64.0**. Catalog tools: **${CATALOG.length}** (${READ_ONLY_COUNT} read-only / ${WRITE_COUNT} write, ${ADMIN_COUNT} admin-gated) plus ${SPECIAL.length} upload tools.`,
);
lines.push("");
lines.push("`*` marks a required parameter. Every write tool triggers a mandatory native approval prompt.");
lines.push("");

const used = new Set();
for (const [title, match] of GROUPS) {
  const items = CATALOG.filter((d) => match(d.name) && !used.has(d.name));
  if (items.length === 0) continue;
  for (const d of items) used.add(d.name);
  lines.push(`## ${title}`);
  lines.push("");
  lines.push("| Tool | Method | Endpoint | Params | Write | Admin |");
  lines.push("| --- | --- | --- | --- | --- | --- |");
  for (const d of items)
    lines.push(
      `| \`${d.name}\` | ${d.method} | \`${d.path}\` | ${paramList(d.params)} | ${d.write ? "yes" : "no"} | ${d.admin ? "yes" : "no"} |`,
    );
  lines.push("");
}

lines.push("## Uploads (special-cased)");
lines.push("");
lines.push("| Tool | Method | Endpoint | Params | Write | Admin |");
lines.push("| --- | --- | --- | --- | --- | --- |");
for (const d of SPECIAL)
  lines.push(
    `| \`${d.name}\` | ${d.method} | \`${d.path}\` | localPath*, path*, asTask | yes | no |`,
  );
lines.push("");
for (const d of SPECIAL) lines.push(`- \`${d.name}\` — ${d.description}`);
lines.push("");

const missed = CATALOG.filter((d) => !used.has(d.name));
if (missed.length) {
  lines.push("## Other");
  lines.push("");
  for (const d of missed) lines.push(`- \`${d.name}\` — ${d.method} \`${d.path}\``);
  lines.push("");
}

await mkdir(resolve(root, "docs"), { recursive: true });
await writeFile(resolve(root, "docs/tools.md"), lines.join("\n"), "utf8");
console.log(`docs/tools.md written: ${CATALOG.length} catalog tools + ${SPECIAL.length} upload tools`);
